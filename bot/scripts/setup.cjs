const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const root = __dirname + '/..';
const example = path.join(root, '.env.example');
const target = path.join(root, '.env');

function parseExample(p) {
  const lines = fs.readFileSync(p, 'utf8').split(/\r?\n/);
  const out = [];
  for (const line of lines) {
    const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (m) out.push([m[1], m[2]]);
  }
  return out;
}

function parseEnv(p) {
  const map = new Map();
  for (const line of fs.readFileSync(p, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (m) map.set(m[1], m[2]);
  }
  return map;
}

if (!fs.existsSync(example)) {
  console.error('Missing .env.example');
  process.exit(1);
}
const vars = parseExample(example);
const existing = fs.existsSync(target) ? parseEnv(target) : new Map();
const lines = ['# Generated by npm run setup', ''];
let created = !fs.existsSync(target);
for (const [k, v] of vars) {
  if (existing.has(k)) {
    let val = existing.get(k);
    if (k === 'AUTH_KEY' && (!val || val === 'change_me_in_production')) {
      val = crypto.randomBytes(24).toString('hex');
    }
    lines.push(`${k}=${val}`);
    continue;
  }
  let val = v;
  if (k === 'AUTH_KEY' && (!val || val === 'change_me_in_production')) {
    val = crypto.randomBytes(24).toString('hex');
  }
  if (k === 'MONGO_URI' && !val) val = 'mongodb://127.0.0.1:27017/deyorbw';
  lines.push(`${k}=${val}`);
}
fs.writeFileSync(target, lines.join('\n'));
if (created) {
  console.log('Created .env from .env.example with generated AUTH_KEY.');
} else {
  console.log('Merged missing keys into .env without overwriting existing values.');
}
console.log('Next: fill DISCORD_TOKEN, CLIENT_ID, GUILD_ID, then run npm run validate.');
